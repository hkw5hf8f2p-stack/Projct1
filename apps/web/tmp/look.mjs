import { chromium } from "playwright";
const [,, url, out, w = "1440", theme = "light", tab = ""] = process.argv;
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: +w, height: 900 }, colorScheme: theme, deviceScaleFactor: 1 });
const p = await ctx.newPage();
const errs = [];
p.on("console", (m) => m.type() === "error" && errs.push(m.text()));
p.on("pageerror", (e) => errs.push("PAGEERR " + e.message));
await p.goto(url + (tab ? (url.includes("?") ? "&" : "?") + "tab=" + tab : ""));
await p.waitForTimeout(3500);
await p.screenshot({ path: out, fullPage: true });
console.log("scrollW", await p.evaluate(() => [document.documentElement.scrollWidth, innerWidth]), errs.slice(0, 5));
await b.close();
